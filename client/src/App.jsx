import { useState, useEffect } from 'react';
import {
  ResponsiveContainer, LineChart, Line, XAxis, YAxis, Tooltip, CartesianGrid,
  BarChart, Bar, PieChart, Pie, Cell,
} from 'recharts';

const COLORS = ['#0f766e', '#2563eb', '#d97706', '#9333ea', '#dc2626', '#4b5563', '#0891b2', '#65a30d'];
const fmt = (n) => (n >= 1000 ? `${(n / 1000).toFixed(1)}k` : n);

function ScoreRing({ score, grade }) {
  const r = 54, c = 2 * Math.PI * r;
  const color = score >= 80 ? '#0f766e' : score >= 60 ? '#2563eb' : score >= 40 ? '#d97706' : '#dc2626';
  return (
    <div className="ring">
      <svg viewBox="0 0 130 130" width="170" height="170" role="img" aria-label={`Health score ${score} of 100`}>
        <circle cx="65" cy="65" r={r} fill="none" stroke="var(--line)" strokeWidth="11" />
        <circle cx="65" cy="65" r={r} fill="none" stroke={color} strokeWidth="11" strokeLinecap="round"
          strokeDasharray={c} strokeDashoffset={c * (1 - score / 100)} transform="rotate(-90 65 65)" />
      </svg>
      <div className="ring-text"><strong>{score}</strong><span>{grade}</span></div>
    </div>
  );
}

function ProjectOverview({ repo }) {
  const [info, setInfo] = useState(null);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState('');

  async function run() {
    setBusy(true); setErr('');
    try {
      const res = await fetch('/api/overview', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ repo }),
      });
      const json = await res.json();
      if (!res.ok) throw new Error(json.error || 'Could not summarise the project.');
      setInfo(json);
    } catch (e) { setErr(e.message); }
    setBusy(false);
  }

  return (
    <section className="ai overview">
      <div className="ai-head">
        <h3>About this project</h3>
        <button onClick={run} disabled={busy}>{busy ? 'Reading README…' : info ? 'Regenerate' : 'Summarise project'}</button>
      </div>
      {!info && !err && !busy && <p className="muted">Get a plain-English explanation of what this project is and who it is for, based on its README.</p>}
      {err && <p className="error" role="alert">{err}</p>}
      {info && (
        <div className="ai-body">
          <p className="verdict">{info.overview}</p>
          {info.audience && <p><b>Who it is for:</b> {info.audience}</p>}
          {info.gettingStarted && <p><b>Getting started:</b> {info.gettingStarted}</p>}
          <div className="ai-cols two">
            {info.keyFeatures.length > 0 && <div><h4>Key features</h4><ul>{info.keyFeatures.map((t) => <li key={t}>{t}</li>)}</ul></div>}
            {info.techStack.length > 0 && (
              <div><h4>Tech stack</h4><p className="chips">{info.techStack.map((t) => <span key={t}>{t}</span>)}</p></div>
            )}
          </div>
          <small>
            {info.usedReadme ? 'Based on the README.' : 'No README found, based on the description only.'} Generated by {info.model} on Groq{info.cached ? ' (cached)' : ''}. AI output can be wrong.
          </small>
        </div>
      )}
    </section>
  );
}

function Analyser({ preset }) {
  const [input, setInput] = useState('');
  const [data, setData] = useState(null);
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);
  const [ai, setAi] = useState(null);
  const [aiError, setAiError] = useState('');
  const [aiLoading, setAiLoading] = useState(false);

  async function summarise() {
    setAiLoading(true); setAiError(''); setAi(null);
    try {
      const res = await fetch('/api/summary', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ repo: data.repo.fullName }),
      });
      const json = await res.json();
      if (!res.ok) throw new Error(json.error || 'Could not generate the summary.');
      setAi(json);
    } catch (err) { setAiError(err.message); }
    setAiLoading(false);
  }

  useEffect(() => {
    if (preset?.repo) { setInput(preset.repo); run(preset.repo); }
  }, [preset]);

  function analyse(e) { e.preventDefault(); run(input); }

  async function run(repo) {
    setLoading(true); setError(''); setData(null); setAi(null); setAiError('');
    try {
      const res = await fetch(`/api/analyse?repo=${encodeURIComponent(repo)}`);
      const json = await res.json();
      if (!res.ok) throw new Error(json.error || 'Something went wrong.');
      setData(json);
    } catch (err) { setError(err.message); }
    setLoading(false);
  }

  return (
    <main>
      <header>
        <h1>GitHub Repo Analyser</h1>
        <p>Paste a public repository and get its health, activity, languages and contributors in one view.</p>
        <form onSubmit={analyse}>
          <input value={input} onChange={(e) => setInput(e.target.value)}
            placeholder="facebook/react or https://github.com/facebook/react" aria-label="Repository" required />
          <button disabled={loading}>{loading ? 'Analysing…' : 'Analyse repository'}</button>
        </form>
        {error && <p className="error" role="alert">{error}</p>}
      </header>

      {data && (
        <>
          <section className="summary">
            <div>
              <h2><a href={data.repo.url} target="_blank" rel="noreferrer">{data.repo.fullName}</a></h2>
              <p>{data.repo.description || 'No description provided.'}</p>
              <ul className="facts">
                <li><b>{fmt(data.repo.stars)}</b> stars</li>
                <li><b>{fmt(data.repo.forks)}</b> forks</li>
                <li><b>{data.repo.openIssues}</b> open / <b>{data.repo.closedIssues}</b> closed issues</li>
                <li>License: <b>{data.repo.license}</b></li>
                <li>Last push: <b>{new Date(data.repo.pushedAt).toLocaleDateString()}</b></li>
              </ul>
              <small>{data.cached ? 'Served from cache' : 'Fresh from GitHub'}, {new Date(data.fetchedAt).toLocaleTimeString()}</small>
            </div>
            <ScoreRing {...data.health} />
          </section>

          <ProjectOverview key={`o-${data.repo.fullName}`} repo={data.repo.fullName} />

          <section className="ai">
            <div className="ai-head">
              <h3>AI summary of the analysis</h3>
              <button onClick={summarise} disabled={aiLoading}>{aiLoading ? 'Generating…' : ai ? 'Regenerate summary' : 'Generate AI summary'}</button>
            </div>
            {!ai && !aiError && !aiLoading && <p className="muted">Get a plain-English verdict, risks and recommendations based on the metrics below (health, activity, contributors).</p>}
            {aiError && <p className="error" role="alert">{aiError}</p>}
            {ai && (
              <div className="ai-body">
                <p className="verdict">{ai.verdict}</p>
                <p><b>Best suited for:</b> {ai.suitableFor}</p>
                <div className="ai-cols">
                  <div><h4>Strengths</h4><ul>{ai.strengths.map((t) => <li key={t}>{t}</li>)}</ul></div>
                  <div><h4>Risks</h4><ul>{ai.risks.map((t) => <li key={t}>{t}</li>)}</ul></div>
                  <div><h4>Recommendations</h4><ul>{ai.recommendations.map((t) => <li key={t}>{t}</li>)}</ul></div>
                </div>
                <small>Generated by {ai.model} on Groq. AI output can be wrong, so check it against the metrics.</small>
              </div>
            )}
          </section>

          <section className="grid">
            <article>
              <h3>Score breakdown</h3>
              {data.health.breakdown.map((p) => (
                <div className="bar-row" key={p.label}>
                  <span>{p.label} <i>({Math.round(p.weight * 100)}%)</i></span>
                  <div className="track"><div style={{ width: `${p.score}%` }} /></div>
                  <b>{p.score}</b>
                </div>
              ))}
            </article>

            <article>
              <h3>Language composition</h3>
              <ResponsiveContainer width="100%" height={220}>
                <PieChart>
                  <Pie data={data.languages} dataKey="percent" nameKey="name" innerRadius={50} outerRadius={85}>
                    {data.languages.map((_, i) => <Cell key={i} fill={COLORS[i % COLORS.length]} />)}
                  </Pie>
                  <Tooltip formatter={(v) => `${v}%`} />
                </PieChart>
              </ResponsiveContainer>
              <p className="legend">
                {data.languages.slice(0, 6).map((l, i) => (
                  <span key={l.name}><em style={{ background: COLORS[i % COLORS.length] }} />{l.name} {l.percent}%</span>
                ))}
              </p>
            </article>

            <article className="wide">
              <h3>Commit activity, last 90 days</h3>
              <p className="stats">
                <span><b>{data.commits.last30}</b> commits in 30 days</span>
                <span><b>{data.commits.avgPerAuthor}</b> avg per author</span>
                <span>Busiest day: <b>{data.commits.peakDay}</b></span>
              </p>
              <ResponsiveContainer width="100%" height={220}>
                <LineChart data={data.commits.timeline}>
                  <CartesianGrid stroke="var(--line)" vertical={false} />
                  <XAxis dataKey="date" tickFormatter={(d) => d.slice(5)} minTickGap={30} />
                  <YAxis allowDecimals={false} width={30} />
                  <Tooltip />
                  <Line type="monotone" dataKey="commits" stroke="#0f766e" strokeWidth={2} dot={false} />
                </LineChart>
              </ResponsiveContainer>
              <h4>Commits by weekday</h4>
              <ResponsiveContainer width="100%" height={140}>
                <BarChart data={data.commits.weekday}>
                  <XAxis dataKey="day" /><YAxis allowDecimals={false} width={30} /><Tooltip />
                  <Bar dataKey="count" fill="#2563eb" radius={[3, 3, 0, 0]} />
                </BarChart>
              </ResponsiveContainer>
              {data.commits.sampled >= 100 && <small>Based on the 100 most recent commits in the window.</small>}
            </article>

            <article className="wide">
              <h3>Top contributors <small>Bus factor: {data.contributors.busFactor}</small></h3>
              <div className="people">
                {data.contributors.top.map((c) => (
                  <a key={c.login} href={c.url} target="_blank" rel="noreferrer">
                    <img src={c.avatar} alt="" width="44" height="44" />
                    <span>{c.login}</span>
                    <small>{fmt(c.contributions)} commits, {c.share}%</small>
                  </a>
                ))}
              </div>
            </article>
          </section>
        </>
      )}
    </main>
  );
}

const STORE_KEY = 'repo-chats';
const uid = () => Date.now().toString(36) + Math.random().toString(36).slice(2, 6);
const blankChat = () => ({ id: uid(), title: 'New chat', messages: [], plan: null, shown: [], updatedAt: Date.now() });

function loadChats() {
  try {
    const saved = JSON.parse(localStorage.getItem(STORE_KEY));
    if (Array.isArray(saved) && saved.length) return saved;
  } catch { /* ignore corrupted storage */ }
  return [blankChat()];
}

const GREETING = 'Tell me what you want to build or learn, and I will find real GitHub repositories for it. Keep refining in this chat, for example "using react" or "more popular ones". Ask for "different ones" to see more results, and start a New chat for a different topic.';

function Chat({ onOpen }) {
  const [chats, setChats] = useState(loadChats);
  const [activeId, setActiveId] = useState(() => chats[0].id);
  const [text, setText] = useState('');
  const [busyIds, setBusyIds] = useState([]);

  // Chat history is saved in the browser's localStorage
  useEffect(() => {
    try { localStorage.setItem(STORE_KEY, JSON.stringify(chats)); } catch { /* storage full or blocked */ }
  }, [chats]);

  const active = chats.find((c) => c.id === activeId) || chats[0];
  const busy = busyIds.includes(active.id);

  // update one chat by id and move it to the top of the list
  const patch = (id, fn) => setChats((cs) => {
    const c = cs.find((x) => x.id === id);
    if (!c) return cs;
    return [{ ...fn(c), updatedAt: Date.now() }, ...cs.filter((x) => x.id !== id)];
  });

  function newChat() {
    if (!active.messages.length) return; // already on an empty chat
    const c = blankChat();
    setChats((cs) => [c, ...cs]);
    setActiveId(c.id);
  }

  function deleteChat(id) {
    const rest = chats.filter((c) => c.id !== id);
    const next = rest.length ? rest : [blankChat()];
    setChats(next);
    if (id === activeId) setActiveId(next[0].id);
  }

  async function send(e) {
    e.preventDefault();
    const q = text.trim();
    const id = active.id;
    if (!q || busy) return;
    const plan = active.plan;
    patch(id, (c) => ({
      ...c,
      title: c.messages.length ? c.title : q.slice(0, 40),
      messages: [...c.messages, { role: 'user', text: q }],
    }));
    setText('');
    setBusyIds((b) => [...b, id]);
    try {
      const res = await fetch('/api/recommend', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ message: q, plan, shown: active.shown || [] }),
      });
      const json = await res.json();
      if (!res.ok) throw new Error(json.error || 'Something went wrong.');
      patch(id, (c) => ({
        ...c,
        plan: json.plan || c.plan,
        shown: [...new Set([...(c.shown || []), ...(json.picks || []).map((r) => r.fullName)])],
        messages: [...c.messages, { role: 'bot', text: json.reply, picks: json.picks }],
      }));
    } catch (err) {
      patch(id, (c) => ({ ...c, messages: [...c.messages, { role: 'bot', text: err.message, isError: true }] }));
    }
    setBusyIds((b) => b.filter((x) => x !== id));
  }

  const p = active.plan;
  return (
    <div className="chat-layout">
      <aside className="sidebar" aria-label="Chat history">
        <button className="new-chat" onClick={newChat}>+ New chat</button>
        <h2 className="side-title">History</h2>
        <ul>
          {chats.map((c) => (
            <li key={c.id} className={c.id === active.id ? 'on' : ''}>
              <button className="title" onClick={() => setActiveId(c.id)} title={c.title}>{c.title}</button>
              <button className="del" onClick={() => deleteChat(c.id)} aria-label={`Delete chat ${c.title}`}>×</button>
            </li>
          ))}
        </ul>
      </aside>

      <section className="chat-main">
        <h1>Find a GitHub repo</h1>
      <div className="chat">
        {p && (
          <p className="focus">
            Focus: <b>{p.keywords.join(', ')}</b>
            {p.kind && p.kind !== 'any' && <> · {p.kind}</>}
            {p.language && <> · {p.language}</>}
            {p.minStars && <> · {fmt(p.minStars)}+ stars</>}
          </p>
        )}
        <div className="log" aria-live="polite">
          {!active.messages.length && <div className="msg bot"><p>{GREETING}</p></div>}
          {active.messages.map((m, i) => (
            <div key={i} className={`msg ${m.role}${m.isError ? ' err' : ''}`}>
              <p>{m.text}</p>
              {m.picks?.map((r) => (
                <div className="pick" key={r.fullName}>
                  <div>
                    <a href={r.url} target="_blank" rel="noreferrer">{r.fullName}</a>
                    <small> {fmt(r.stars)} stars{r.language ? `, ${r.language}` : ''}</small>
                    <p>{r.reason}</p>
                    {r.caveat && <p className="caveat">Heads up: {r.caveat}</p>}
                  </div>
                  <button onClick={() => onOpen(r.fullName)}>Analyse this repo</button>
                </div>
              ))}
            </div>
          ))}
          {busy && <div className="msg bot"><p>Searching GitHub and reading READMEs…</p></div>}
        </div>
        <form onSubmit={send}>
          <input value={text} onChange={(e) => setText(e.target.value)} maxLength={500}
            placeholder={active.messages.length ? 'Refine your search…' : 'Describe what you are looking for…'} aria-label="Your request" />
          <button disabled={busy}>Send</button>
        </form>
        </div>
      </section>
    </div>
  );
}

export default function App() {
  const [tab, setTab] = useState('chat');
  const [preset, setPreset] = useState(null);
  return (
    <>
      <nav className="tabs">
        <button className={tab === 'chat' ? 'on' : ''} onClick={() => setTab('chat')}>Find a repo</button>
        <button className={tab === 'analyse' ? 'on' : ''} onClick={() => setTab('analyse')}>Analyse a repo</button>
      </nav>
      <div hidden={tab !== 'chat'}>
        <Chat onOpen={(repo) => { setPreset({ repo, n: Date.now() }); setTab('analyse'); }} />
      </div>
      <div hidden={tab !== 'analyse'}><Analyser preset={preset} /></div>
    </>
  );
}
